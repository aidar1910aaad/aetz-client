/**
 * Форматирует сумму: округляет до целого числа и форматирует с пробелами
 * @param amount - сумма для форматирования
 * @returns отформатированная строка (например: "1 974 123 731")
 */
export const formatAmount = (amount: number): string => {
  // Округляем до целого числа
  const rounded = Math.round(amount);
  // Преобразуем в строку (убираем дробную часть если есть)
  const parts = rounded.toString().split('.')[0];
  // Форматируем с пробелами: разбиваем на группы по 3 цифры с конца
  return parts.replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
};

